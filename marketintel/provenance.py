"""Portable, deterministic dataset provenance and saved research briefs."""
from __future__ import annotations

import hashlib
import json
from datetime import datetime, timezone
from pathlib import Path

import numpy as np

from .storage import records


def vector_fingerprint(ids: list[str], vectors: np.ndarray) -> str:
    """SHA-256 of logical IDs and vector contents (not NPZ ZIP timestamps)."""
    data = np.ascontiguousarray(vectors, dtype=np.float32)
    checksum = hashlib.sha256()
    checksum.update(json.dumps(ids, ensure_ascii=False, separators=(',', ':')).encode('utf-8'))
    checksum.update(json.dumps(list(data.shape)).encode('ascii'))
    checksum.update(data.tobytes())
    return checksum.hexdigest()


def attach_provenance(result: dict, ids: list[str], vectors: np.ndarray,
                      feature_type: str, source: str = 'uploaded-documents') -> dict:
    """Attach the exact input snapshot to a real computed result."""
    manifest = {d['doc_id']: {'filename': d['filename'], 'industry': d.get('industry', 'Unspecified')}
                for d in records()}
    result['metadata'].update({
        'input_type': source,
        'vector_type': feature_type,
        'input_sha256': vector_fingerprint(ids, vectors),
        'source_documents': [{'doc_id': d, **manifest.get(d, {'filename': d, 'industry': 'Unknown'})}
                             for d in ids],
        'created_utc': datetime.now(timezone.utc).isoformat(),
    })
    return result


def research_brief(result: dict) -> str:
    """Make a traceable, non-generative research brief from actual computation.

    This is deliberately NOT presented as an LLM-generated insight, prediction,
    investment recommendation or industry ranking.
    """
    meta = result.get('metadata', {})
    names = {item['doc_id']: item.get('filename', item['doc_id'])
             for item in meta.get('source_documents', [])}
    lines = [
        '# Analysis brief',
        '',
        '**Method:** ' + str(meta.get('algorithm', 'See saved result metadata')),
        '**Execution:** ' + str(meta.get('mode', 'unknown')),
        '**Documents:** ' + str(meta.get('documents', '?')),
        '**Feature representation:** ' + str(meta.get('vector_type', 'not recorded')),
        '**Dataset fingerprint:** `' + str(meta.get('input_sha256', 'not recorded')) + '`',
        '',
        '## Computed findings',
    ]
    if 'matches' in result:
        matches = result['matches']
        lines.append(f'Calculated {len(matches)} directed document-to-document top-k matches.')
        strongest = sorted(matches, key=lambda item: (-item['score'], item['doc_id'], item['similar_doc_id']))[:8]
        if strongest:
            lines.extend(['', '| Document | Similar report | Cosine similarity |', '|---|---|---:|'])
            for match in strongest:
                name_a = names.get(match['doc_id'], match['doc_id']).replace('|', '/')
                name_b = names.get(match['similar_doc_id'], match['similar_doc_id']).replace('|', '/')
                lines.append(f"| {name_a} | {name_b} | {match['score']:.4f} |")
    elif 'assignments' in result:
        from collections import Counter
        groups = Counter(x['cluster_id'] for x in result['assignments'])
        lines.append('K-Means grouped document feature vectors into the following unlabeled clusters:')
        lines.extend([f'- Cluster {cid}: {total} documents' for cid, total in sorted(groups.items())])
        lines.append('Cluster numbers are arbitrary; labels are **not** market forecasts or verified industry names.')
    else:
        lines.append('No recognized analytical result is available.')

    lines.extend(['', '## Source traceability'])
    for item in meta.get('source_documents', [])[:20]:
        lines.append(f"- {item['filename']} (`{item['doc_id']}`); industry: {item.get('industry', 'Unspecified')}")
    if not meta.get('source_documents'):
        lines.append('No document manifest was attached. This may be a standalone benchmark dataset.')

    lines.extend(['', '## Interpretation and limitations',
                  '- Similarity measures proximity of the selected numerical text representation, not future market growth.',
                  '- Clusters group features and are not validated industry classifications.',
                  '- Numerical market claims require independently verified, comparable source metrics.',
                  '- This brief is generated by a deterministic report template, **not** a language model.',
                  '- Local MPI ranks do not establish multi-node AWS execution.', ''])
    return '\n'.join(lines)
